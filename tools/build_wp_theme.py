#!/usr/bin/env python3
"""Build the Roof Crew WordPress theme from the v2 static site generator.

The static generator (tools/build_v2.py) and its copy (tools/content_v2.py) stay the source. This
script renders the same pages with WordPress-aware links, writes the generated templates and
partials into wordpress/roofcrew-theme/, writes the starter content (inc/seed.php) and the old
address redirects (inc/redirects.php), copies the assets and zips the theme.

Hand-written theme files (functions.php, inc/ apart from seed.php and redirects.php,
template-service.php, template-location.php, page.php, index.php, 404.php, style.css, wp.css) live in
the theme folder and are not touched.

Run from the repo root:  python3 tools/build_wp_theme.py
Output: wordpress/roofcrew-theme/ and wordpress/roofcrew-theme.zip
"""
import importlib.util, os, re, shutil, zipfile, json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THEME = os.path.join(ROOT, "wordpress", "roofcrew-theme")

spec = importlib.util.spec_from_file_location("bv", os.path.join(ROOT, "tools", "build_v2.py"))
bv = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bv)
C = bv.C

ASSET = "<?php echo rc_theme_uri(); ?>/"
GEN = "<?php /* Generated by tools/build_wp_theme.py from the v2 design. Edit the generator, not this file. */ ?>\n"


class WPPage(bv.Page):
    """Same interface as the static Page, but every link is a WordPress URL."""

    def __init__(self, path):
        self.path = path
        self.r = ASSET

    def u(self, target):
        if target.startswith("#"):
            return f"<?php echo rc_url(); ?>{target}"
        anchor = ""
        if "#" in target:
            target, anchor = target.split("#", 1)
            anchor = "#" + anchor
        return f"<?php echo rc_url('{target.strip('/')}'); ?>{anchor}"

    def link(self, path, cls=""):
        # Published pages link normally; drafts or missing pages become a disabled "soon" link.
        return f"<?php echo rc_link('{path.strip('/')}'" + (f", '{cls}'" if cls else "") + "); ?>"


# Dynamic pieces: these lists come from the pages in WordPress, so new or duplicated
# Services and Locations pages appear automatically.
bv.services_grid = lambda pg, wide=False: f"<?php rc_services_grid({'true' if wide else 'false'}); ?>"

captured = {}


def capture(pg, title, desc, current, body, schema=None):
    captured[pg.path] = dict(title=title, desc=desc, body=body, schema=schema or [])


bv.page = capture


def wpify(html, path):
    # Asset paths written relative to the home page (images, the project slider data).
    html = re.sub(r'(?<=["\'(])assets/', ASSET + 'assets/', html)
    if path != "quote/":
        html = html.replace('href="#get-quote"', 'href="<?php echo rc_url(\'quote\'); ?>"')
    # Quote forms post to WordPress and show the thank-you after the redirect.
    html = re.sub(r'(<div class="quote-card" id="([\w-]+)">.*?)<form class="form" data-quote>',
                  r"\1<?php rc_form_open('\2'); ?>", html, flags=re.S)
    html = re.sub(r'<div class="quote-card" id="([\w-]+)">',
                  lambda m: '<div class="quote-card<?php echo rc_sent( \'%s\' ) ? \' is-sent\' : \'\'; ?>" id="%s">' % (m.group(1), m.group(1)), html)
    html = html.replace('<strong>Thanks, <span data-first></span>.</strong>', "<strong>Thanks<?php echo rc_sent_name(); ?>.</strong>")
    html = html.replace(" (Staging preview: this form is not connected yet.)", "")
    html = html.replace('<p class="full fine">',
                        '<div class="full hp" aria-hidden="true"><label>Leave this empty<input name="website" tabindex="-1" autocomplete="off"></label></div>\n'
                        '    <p class="full fine">')
    return html


def write(rel, text):
    dest = os.path.join(THEME, rel)
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    with open(dest, "w", encoding="utf-8") as f:
        f.write(text)


def ld(schema):
    return "".join(f'<script type="application/ld+json">{json.dumps(s, ensure_ascii=False)}</script>' for s in schema)


def template(slug, path, name):
    c = captured[path]
    head = f"<?php\n/* {name}. Generated from the v2 design by tools/build_wp_theme.py: edit the generator, not this file. */\n"
    head += f"rc_meta( {json.dumps(c['title'])}, {json.dumps(c['desc'])} );\nget_header(); ?>\n"
    write(slug, head + ld(c["schema"]) + "\n" + wpify(c["body"], path) + "\n<?php get_footer();\n")


def block_html(html):
    """Editor content as blocks: H2 headings as Heading blocks, the rest as Custom HTML blocks
    (so WordPress keeps the markup and the yellow highlights as they are)."""
    out = []
    for part in re.split(r"(?=<h2>)", html):
        m = re.match(r"<h2>(.*?)</h2>(.*)$", part, re.S)
        if m:
            out.append(f'<!-- wp:heading -->\n<h2 class="wp-block-heading">{m.group(1)}</h2>\n<!-- /wp:heading -->')
            part = m.group(2)
        if part.strip():
            out.append(f"<!-- wp:html -->\n{part}\n<!-- /wp:html -->")
    return "\n\n".join(out)


def faqs_field(items):
    return "\n\n".join(f"{q}\n{a}" for q, a in items)


def seed_services():
    out = []
    for i, s in enumerate(C.SERVICE_PAGES):
        secs = s["sections"]
        first = secs[0][1] if secs else ""
        content = bv.fill(first) + "".join(f"<h2>{h}</h2>{bv.fill(html)}" for h, html in secs[1:])
        out.append(dict(slug=s["slug"], title=bv.strip_tags(s["name"]), root=s["kind"] == "material", publish=True,
                        excerpt=s["card"], image=s["hero"], content=block_html(content),
                        fields=dict(rc_kind=s["kind"], rc_h1=s["h1"], rc_lede=s["lede"], rc_hold=s.get("hold", ""),
                                    rc_intro_heading=secs[0][0] if secs else "", rc_included="", rc_photo=s["photo"],
                                    rc_icon=s["icon"], rc_reroof="1" if s.get("reroof") else "",
                                    rc_faq_title=s["faq_h"], rc_faqs=faqs_field(s["faqs"]), rc_closing=s["closing"],
                                    rc_meta_title=s["title"], rc_meta_desc=s["desc"])))
    return out


def seed_locations():
    out = []
    order = [l["slug"] for l in C.REGIONS] + C.LOCATIONS_PAGE["popular"]
    for l in sorted(C.LOCATION_PAGES, key=lambda l: order.index(l["slug"])):
        content = l["local"] + (f"<h2>{l['cost'][0]}</h2>{l['cost'][1]}" if l.get("cost") else "")
        review = l.get("review")
        review = "" if not review else (review if isinstance(review, str) else f"{review[0]}\n{review[1]}")
        subs = [bv.P(s, l["suburbs_q"]) if l.get("suburbs_q") else s for s in l["suburbs"]]
        out.append(dict(slug=l["slug"], title=l["name"], root=not l["path"].startswith("locations/"), publish=True,
                        excerpt=l.get("blurb", l["lede"]), image=l["hero"], content=block_html(content),
                        fields=dict(rc_kind=l["kind"], rc_region=l.get("region", ""), rc_h1=l["h1"], rc_lede=l["lede"],
                                    rc_intro_heading=l["local_h"], rc_job=l.get("job", ""), rc_photo=l.get("photo", ""),
                                    rc_review=review, rc_faq_title=l.get("faq_h", ""), rc_faqs=faqs_field(l["faqs"]),
                                    rc_suburbs="\n".join(subs), rc_map=l["map"], rc_meta_title=l["title"], rc_meta_desc=l["desc"])))
    return out


def seed_posts():
    to = lambda t: "/" + t
    return [dict(slug=p["slug"], title=p["title"], date=p["date"], image=p["image"], excerpt=bv.excerpt(p, 40).rstrip("…"),
                 content=bv.live_links(p["html"], to)) for p in C.POSTS]


def main():
    # ---- pages with a fixed layout
    pg_cls = bv.Page
    bv.Page = WPPage
    try:
        for b in (bv.build_home, bv.build_about, bv.build_contact, bv.build_quote, bv.build_services, bv.build_locations, bv.build_blog):
            b()
        bv.build_post(dict(C.POSTS[0], slug="__post__", title="__TITLE__", date="2000-01-01", image="__IMG__", html="__CONTENT__"))
    finally:
        bv.Page = pg_cls

    # Home: the region buttons come from the Locations pages.
    home = captured[""]
    home["body"] = re.sub(r'<div class="region-links">.*?<a class="ask"', '<div class="region-links"><?php rc_region_links(); ?><a class="ask"', home["body"], flags=re.S)
    # Locations index: region cards and popular area cards come from the pages.
    loc = captured["locations/"]
    loc["body"] = re.sub(r'<div class="grid-4" data-regions>.*?</a></div>', "<div class=\"grid-4\" data-regions><?php rc_region_cards( 'region' ); ?></div>", loc["body"], flags=re.S)
    loc["body"] = re.sub(r'<div class="grid-3" data-areas>.*?</a></div>', "<div class=\"grid-3\" data-areas><?php rc_region_cards( 'area' ); ?></div>", loc["body"], flags=re.S)
    # Blog index: the posts loop.
    blog = captured["blog/"]
    blog["body"] = re.sub(r'<div class="grid-3 posts">.*?</a></div>', '''<div class="grid-3 posts"><?php while ( have_posts() ) : the_post(); ?><a class="card post-card" href="<?php the_permalink(); ?>"><div class="img"><?php if ( has_post_thumbnail() ) { the_post_thumbnail( 'medium_large', array( 'alt' => '' ) ); } ?></div><div class="body"><small><?php echo esc_html( get_the_date( 'j F Y' ) ); ?></small><h3><?php the_title(); ?></h3><p><?php echo esc_html( wp_trim_words( get_the_excerpt(), 26 ) ); ?></p><span class="link">Read more →</span></div></a><?php endwhile; ?></div>
<?php the_posts_pagination(); ?>''', blog["body"], flags=re.S)
    template("front-page.php", "", "Home page")
    template("page-about.php", "about/", "About page")
    template("page-contact.php", "contact/", "Contact page")
    template("page-quote.php", "quote/", "Free quote page")
    template("page-services.php", "services/", "Services (all services)")
    template("page-locations.php", "locations/", "Locations (all areas)")
    template("home.php", "blog/", "Blog (the posts page)")

    # Single post, from the static post layout with the post's parts swapped in.
    post = captured["__post__/"]
    body = wpify(post["body"], "__post__/")
    body = body.replace("1 January 2000", "<?php echo esc_html( get_the_date( 'j F Y' ) ); ?>").replace("__TITLE__", "<?php the_title(); ?>")
    body = re.sub(r'<figure class="post-img">.*?</figure>', "<?php if ( has_post_thumbnail() ) : ?><figure class=\"post-img\"><?php the_post_thumbnail( 'large', array( 'alt' => '' ) ); ?></figure><?php endif; ?>", body, flags=re.S)
    body = body.replace("__CONTENT__", "<?php the_content(); ?>")
    body = re.sub(r'(<h3>More from the blog</h3><ul class="ticks">).*?(</ul>)',
                  r"""\1<?php foreach ( get_posts( array( 'numberposts' => 6, 'exclude' => array( get_the_ID() ) ) ) as $rc_p ) : ?><li><a class="link" href="<?php echo esc_url( get_permalink( $rc_p ) ); ?>"><?php echo esc_html( get_the_title( $rc_p ) ); ?></a></li><?php endforeach; ?>\2""", body, flags=re.S)
    write("single.php", "<?php\n/* A blog post. Generated from the v2 design by tools/build_wp_theme.py: edit the generator, not this file. */\n"
          "the_post();\nrc_meta( get_the_title() . ' | The Roof Crew', wp_strip_all_tags( get_the_excerpt() ) );\nget_header(); ?>\n"
          + body + "\n<?php get_footer();\n")

    # ---- shared partials used by the Service and Location templates
    pg = WPPage("x/")
    write("parts/reroof-extra.php", GEN + wpify(bv.reroof_extra(pg), "x/"))
    write("parts/reviews.php", GEN + bv.reviews_row(pg))
    local = bv.reviews_row(pg, local=("__LOCAL__", "__CITE__"))
    local = re.sub(r'<figure class="card review"><div class="stars">★★★★★</div><blockquote>__LOCAL__</blockquote><cite>__CITE__</cite></figure>', "<?php rc_local_review(); ?>", local)
    assert "rc_local_review" in local
    write("parts/reviews-local.php", GEN + local)
    closing = bv.closing(pg, "New roof (reroof)", "__HEADING__")
    closing = closing.replace("__HEADING__", "<?php echo esc_html( isset( $args['heading'] ) ? $args['heading'] : 'Your roof, your real number.' ); ?>")
    write("parts/closing.php", GEN + wpify(closing, "x/"))
    for old in ("parts/signs.php", "parts/systems.php", "parts/pricing.php", "parts/faqs.php", "parts/faq-schema.php", "parts/before-after.php", "parts/review-one.php"):
        if os.path.exists(os.path.join(THEME, old)):
            os.remove(os.path.join(THEME, old))

    # ---- starter content (Import starter content) and old address redirects
    seed = dict(services=seed_services(), locations=seed_locations(), posts=seed_posts(),
                privacy=dict(title=C.PRIVACY["title"], content=C.PRIVACY["html"]))
    seed = json.dumps(seed, ensure_ascii=False, indent=1)
    assert "\nJSON" not in seed
    write("inc/seed.php", "<?php\n/* Starter pages and posts for Import starter content. Generated by tools/build_wp_theme.py from tools/content_v2.py. */\nreturn json_decode( <<<'JSON'\n" + seed + "\nJSON\n, true );\n")
    write("inc/redirects.php", "<?php\n/* Old address => new page. Generated by tools/build_wp_theme.py from tools/content_v2.py. */\nreturn array(\n"
          + "".join(f"\t{json.dumps(o.strip('/'))} => {json.dumps(n.strip('/'))},\n" for o, n in C.REDIRECTS.items()) + ");\n")

    write("parts/icons.php", "<?php\n/* SVG icons used by the templates. Generated by tools/build_wp_theme.py. */\nreturn " +
          "array(\n" + "".join(f"\t{json.dumps(k)} => {json.dumps(v)},\n" for k, v in bv.ICONS.items()) + ");\n")

    # ---- header and footer: the Services and Locations lists come from the pages
    pg = WPPage("")
    keep = bv.NAV_SERVICES, bv.NAV_REGIONS, bv.FOOT_SERVICES
    bv.NAV_SERVICES, bv.NAV_REGIONS, bv.FOOT_SERVICES = [], [], []
    try:
        hdr = bv.header(pg, "")
        ftr = bv.footer(pg)
    finally:
        bv.NAV_SERVICES, bv.NAV_REGIONS, bv.FOOT_SERVICES = keep

    def must(text, old, new):
        assert old in text, old
        return text.replace(old, new)
    hdr = must(hdr, "All services</a></div>", "All services</a><?php rc_menu( 'services' ); ?></div>")
    hdr = must(hdr, "All areas we cover</a></div>", "All areas we cover</a><?php rc_menu( 'locations', false, 'region' ); ?></div>")
    hdr = must(hdr, '<button aria-expanded="false">Services', '<button aria-expanded="false"<?php echo rc_current( \'services\' ); ?>>Services')
    hdr = must(hdr, '<button aria-expanded="false">Locations', '<button aria-expanded="false"<?php echo rc_current( \'locations\' ); ?>>Locations')
    hdr = must(hdr, "about'); ?>\">About</a>", "about'); ?>\"<?php echo rc_current( 'about' ); ?>>About</a>")
    hdr = must(hdr, "blog'); ?>\">Blog</a>", "blog'); ?>\"<?php echo rc_current( 'blog' ); ?>>Blog</a>")
    hdr = hdr.replace('href="#get-quote"', 'href="<?php echo rc_url(\'quote\'); ?>"')
    ftr = must(ftr, "<h4>Services</h4><ul></ul>", "<h4>Services</h4><ul><?php rc_menu( 'services', true, 'service' ); ?></ul>")
    ftr = must(ftr, "All areas</a></li></ul>", "All areas</a></li><?php rc_menu( 'locations', true, 'region' ); ?></ul>")
    ftr = ftr.replace('href="#get-quote"', 'href="<?php echo rc_url(\'quote\'); ?>"')
    ftr = must(ftr, "<span>Staging preview, not live</span>", "")
    ftr = re.sub(r'\n<script src="[^"]*site\.js"></script>', "", ftr)
    ftr = must(ftr, "© The Roof Crew, Auckland", "© <?php echo esc_html( gmdate( 'Y' ) ); ?> The Roof Crew, Auckland")
    write("header.php", f'''<?php /* Generated by tools/build_wp_theme.py from the v2 design. Edit the generator, not this file. */ ?>
<!doctype html>
<html <?php language_attributes(); ?>>
<head>
<meta charset="<?php bloginfo( 'charset' ); ?>">
<meta name="viewport" content="width=device-width, initial-scale=1">
<?php wp_head(); ?>
</head>
<body <?php body_class(); ?>>
<?php wp_body_open(); ?>
{hdr}
<main>
''')
    write("footer.php", GEN + f'''</main>
{ftr}
<?php wp_footer(); ?>
</body>
</html>
''')

    # ---- assets (images, css, js, icons) from the static site
    for sub in ("css", "js", "icons", "img"):
        src = os.path.join(bv.OUT, "assets", sub)
        dst = os.path.join(THEME, "assets", sub)
        if os.path.isdir(dst):
            shutil.rmtree(dst)
        shutil.copytree(src, dst)
    shutil.copy2(os.path.join(THEME, "assets", "icons", "logo.png"), os.path.join(THEME, "screenshot.png")) if not os.path.exists(os.path.join(THEME, "screenshot.png")) else None

    # Sanity check: no static-only links left in generated templates.
    for d, _, fs in os.walk(THEME):
        for f in fs:
            if f.endswith(".php"):
                t = open(os.path.join(d, f), encoding="utf-8").read()
                assert 'href="../' not in t and "data-quote" not in t, f

    zpath = os.path.join(ROOT, "wordpress", "roofcrew-theme.zip")
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for d, _, fs in sorted(os.walk(THEME)):
            for f in sorted(fs):
                full = os.path.join(d, f)
                z.write(full, os.path.join("roofcrew-theme", os.path.relpath(full, THEME)))
    print("theme built:", zpath)


if __name__ == "__main__":
    main()
