#!/usr/bin/env python3
"""Build the Roof Crew WordPress theme from the v2 static site generator.

The static generator (tools/build_v2.py) stays the design source. This script renders the same
pages with WordPress-aware links, writes the generated templates and partials into
wordpress/roofcrew-theme/, copies the assets and zips the theme.

Hand-written theme files (functions.php, inc/, template-service.php, template-location.php,
page.php, index.php, 404.php, style.css) live in the theme folder and are not touched.

Run from the repo root:  python3 tools/build_wp_theme.py
Output: wordpress/roofcrew-theme/ and wordpress/roofcrew-theme.zip
"""
import importlib.util, os, re, shutil, zipfile, json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THEME = os.path.join(ROOT, "wordpress", "roofcrew-theme")

spec = importlib.util.spec_from_file_location("bv", os.path.join(ROOT, "tools", "build_v2.py"))
bv = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bv)

ASSET = "<?php echo rc_theme_uri(); ?>/"
GEN = "<?php /* Generated by tools/build_wp_theme.py from the v2 design. Edit the generator, not this file. */ ?>\n"


class WPPage(bv.Page):
    """Same interface as the static Page, but every link is a WordPress URL."""

    def __init__(self, path):
        self.path = path
        self.r = ASSET

    def u(self, target):
        if target.startswith("#"):
            return f"<?php echo rc_url(); ?>{target}"
        anchor = ""
        if "#" in target:
            target, anchor = target.split("#", 1)
            anchor = "#" + anchor
        return f"<?php echo rc_url('{target.strip('/')}'); ?>{anchor}"

    def svc_link(self, slug, built):
        return f"<?php echo rc_link('services/{slug}'); ?>"

    def region_link(self, slug, built, cls=""):
        return f"<?php echo rc_link('locations/{slug}', '{cls}'); ?>"


# Dynamic pieces: these lists come from the child pages in WordPress, so new or duplicated
# Services and Locations pages appear automatically.
bv.services_grid = lambda pg, wide=False: f"<?php rc_services_grid({'true' if wide else 'false'}); ?>"

captured = {}


def capture(pg, title, desc, current, body, schema=None):
    captured[pg.path] = dict(title=title, desc=desc, body=body, schema=schema or [])


bv.page = capture


def wpify(html, path):
    # Asset paths written relative to the home page (images, the project slider data).
    html = re.sub(r'(?<=["\'(])assets/', ASSET + 'assets/', html)
    # A link class plus rc_link(): let rc_link print the classes so "soon" can be added to them.
    html = re.sub(r'class="([^"]*)" <\?php echo rc_link\(\'([^\']*)\'\); \?>', r"<?php echo rc_link('\2', '\1'); ?>", html)
    if path != "quote/":
        html = html.replace('href="#get-quote"', 'href="<?php echo rc_url(\'quote\'); ?>"')
    # Quote forms post to WordPress and show the thank-you after the redirect.
    html = re.sub(r'(<div class="quote-card" id="([\w-]+)">.*?)<form class="form" data-quote>',
                  r"\1<?php rc_form_open('\2'); ?>", html, flags=re.S)
    html = re.sub(r'<div class="quote-card" id="([\w-]+)">',
                  lambda m: '<div class="quote-card<?php echo rc_sent( \'%s\' ) ? \' is-sent\' : \'\'; ?>" id="%s">' % (m.group(1), m.group(1)), html)
    html = html.replace('<strong>Thanks, <span data-first></span>.</strong>', "<strong>Thanks<?php echo rc_sent_name(); ?>.</strong>")
    html = html.replace(" (Staging preview: this form is not connected yet.)", "")
    html = html.replace('<p class="full fine">Mike will call you back personally. No sales pressure.</p>',
                        '<div class="full hp" aria-hidden="true"><label>Leave this empty<input name="website" tabindex="-1" autocomplete="off"></label></div>\n'
                        '    <p class="full fine">Mike will call you back personally. No sales pressure.</p>')
    return html


def write(rel, text):
    dest = os.path.join(THEME, rel)
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    with open(dest, "w", encoding="utf-8") as f:
        f.write(text)


def template(slug, path, name):
    c = captured[path]
    ld = "".join(f'<script type="application/ld+json">{json.dumps(s, ensure_ascii=False)}</script>' for s in c["schema"])
    head = f"<?php\n/* {name}. Generated from the v2 design by tools/build_wp_theme.py: edit the generator, not this file. */\n"
    head += f"rc_meta( {json.dumps(c['title'])}, {json.dumps(c['desc'])} );\nget_header(); ?>\n"
    write(slug, head + ld + "\n" + wpify(c["body"], path) + "\n<?php get_footer();\n")


def main():
    # ---- pages with a fixed layout
    for b in (bv.build_home, bv.build_about, bv.build_contact, bv.build_quote, bv.build_services, bv.build_locations):
        pg_cls = bv.Page
        bv.Page = WPPage
        try:
            b()
        finally:
            bv.Page = pg_cls

    # Home: the region buttons come from the Locations child pages.
    home = captured[""]
    home["body"] = re.sub(r'<div class="region-links">.*?<a class="ask"', '<div class="region-links"><?php rc_region_links(); ?><a class="ask"', home["body"], flags=re.S)
    # Locations index: region cards come from the child pages.
    loc = captured["locations/"]
    loc["body"] = re.sub(r'<div class="grid-4"><a class="card region-card".*?</a></div>', '<div class="grid-4"><?php rc_region_cards(); ?></div>', loc["body"], flags=re.S)

    template("front-page.php", "", "Home page")
    template("page-about.php", "about/", "About page")
    template("page-contact.php", "contact/", "Contact page")
    template("page-quote.php", "quote/", "Free quote page")
    template("page-services.php", "services/", "Services (all services)")
    template("page-locations.php", "locations/", "Locations (all areas)")

    # ---- shared partials used by the Service and Location templates
    pg = WPPage("x/")
    write("parts/signs.php", GEN + bv.signs_list())
    write("parts/systems.php", GEN + bv.systems_cards(pg))
    write("parts/pricing.php", GEN + wpify(bv.pricing_panel(pg, "What a reroof roughly costs"), "x/"))
    write("parts/reviews.php", GEN + bv.reviews_row(pg))
    write("parts/faqs.php", GEN + bv.faq_block(bv.HOME_FAQS))
    write("parts/faq-schema.php", GEN + f'<script type="application/ld+json">{json.dumps(bv.faq_schema(bv.HOME_FAQS), ensure_ascii=False)}</script>')
    closing = bv.closing(pg, "New roof (reroof)", "__HEADING__")
    closing = closing.replace("__HEADING__", "<?php echo esc_html( isset( $args['heading'] ) ? $args['heading'] : 'Your roof, your real number.' ); ?>")
    write("parts/closing.php", GEN + wpify(closing, "x/"))
    p = bv.PROJECTS["p2"]
    write("parts/before-after.php", GEN + f'''<div class="ba"><img class="before" src="{ASSET}assets/img/{p[0]}" alt="Before the reroof"><img class="after" src="{ASSET}assets/img/{p[1]}" alt="{p[2]}">
    <span class="lbl l">Before</span><span class="lbl r">After</span><div class="handle"></div><div class="knob">‹›</div><input type="range" min="0" max="100" value="50" aria-label="Compare before and after"></div>''')
    write("parts/review-one.php", GEN + bv.reviews_row(pg, "reroof"))

    # ---- starter content for the Services and Locations child pages (Import starter content)
    services = []
    for slug, name, short, built in bv.SERVICES:
        item = dict(slug=slug, title=name, excerpt=short, publish=built, image="", content=f"<!-- wp:paragraph -->\n<p>{short}</p>\n<!-- /wp:paragraph -->",
                    fields=dict(rc_h1=f"{name} in Auckland", rc_lede=short, rc_intro_heading="", rc_included="", rc_icon=bv.SVC_ICON[slug], rc_reroof=""))
        if slug == "reroofing":
            item.update(image="hero-metal-tile.jpg", content="<!-- wp:paragraph -->\n<p>We strip your old roof, dispose of it responsibly and install new underlay, flashings, ridge capping and your choice of roofing, all under full scaffolding.</p>\n<!-- /wp:paragraph -->")
            item["fields"].update(rc_h1="Reroofing in Auckland", rc_lede="Old roof leaking, rusting or just tired? A new roof is the biggest upgrade you can make to your home, and the first thing a buyer notices.",
                                  rc_intro_heading="Same house. A completely new roof.", rc_reroof="1",
                                  rc_included="\n".join(["Old roof stripped and disposed of responsibly", "New underlay, flashings and ridge capping", "Rotten battens or purlins found and replaced",
                                                         "Full scaffolding and edge protection", "Fully guaranteed workmanship and product", "Finance available"]))
        services.append(item)
    locations = []
    for slug, name, blurb, built in bv.REGIONS:
        subs = [s.strip() for s in blurb.replace(" and nearby", "").split(",")]
        item = dict(slug=slug, title=name, excerpt=blurb, publish=built, image="",
                    content=f"<!-- wp:paragraph -->\n<p>From {subs[0]} to {subs[-1]}, the same family crew quotes, builds and guarantees every roof.</p>\n<!-- /wp:paragraph -->",
                    fields=dict(rc_h1=f"Reroofing in {name}", rc_lede=f"Free, no-pressure reroof quotes across {name}.", rc_intro_heading="Your local reroofing crew.", rc_suburbs="\n".join(subs), rc_map=""))
        if slug == "east-auckland":
            item.update(image="bg-sunset.jpg", content="<!-- wp:paragraph -->\n<p>From Howick to Beachlands, the same family crew quotes, builds and guarantees every roof.</p>\n<!-- /wp:paragraph -->")
            item["fields"].update(rc_lede="Free, no-pressure reroof quotes from Howick and Pakuranga to Flat Bush and Beachlands.", rc_suburbs="\n".join(bv.EAST_SUBURBS), rc_map=bv.MAP_EAST)
        locations.append(item)
    seed = json.dumps(dict(services=services, locations=locations), ensure_ascii=False, indent=1)
    assert "\nJSON" not in seed
    write("inc/seed.php", "<?php\n/* Starter pages for Import starter content. Generated by tools/build_wp_theme.py. */\nreturn json_decode( <<<'JSON'\n" + seed + "\nJSON\n, true );\n")

    write("parts/icons.php", "<?php\n/* SVG icons used by the templates. Generated by tools/build_wp_theme.py. */\nreturn " +
          "array(\n" + "".join(f"\t{json.dumps(k)} => {json.dumps(v)},\n" for k, v in bv.ICONS.items()) + ");\n")

    # ---- header and footer: the Services and Locations lists come from the child pages
    pg = WPPage("")
    svcs, regs = bv.SERVICES, bv.REGIONS
    bv.SERVICES, bv.REGIONS = [], []
    try:
        hdr = bv.header(pg, "")
        ftr = bv.footer(pg)
    finally:
        bv.SERVICES, bv.REGIONS = svcs, regs
    hdr = hdr.replace("All services</a></div>", "All services</a><?php rc_menu( 'services' ); ?></div>")
    hdr = hdr.replace("All areas we cover</a></div>", "All areas we cover</a><?php rc_menu( 'locations' ); ?></div>")
    hdr = hdr.replace('<button aria-expanded="false">Services', '<button aria-expanded="false"<?php echo rc_current( \'services\' ); ?>>Services')
    hdr = hdr.replace('<button aria-expanded="false">Locations', '<button aria-expanded="false"<?php echo rc_current( \'locations\' ); ?>>Locations')
    hdr = hdr.replace("about'); ?>\">About</a>", "about'); ?>\"<?php echo rc_current( 'about' ); ?>>About</a>")
    hdr = hdr.replace('href="#get-quote"', 'href="<?php echo rc_url(\'quote\'); ?>"')
    ftr = ftr.replace("<h4>Services</h4><ul></ul>", "<h4>Services</h4><ul><?php rc_menu( 'services', true ); ?></ul>")
    ftr = ftr.replace("All areas</a></li></ul>", "All areas</a></li><?php rc_menu( 'locations', true ); ?></ul>")
    ftr = ftr.replace('href="#get-quote"', 'href="<?php echo rc_url(\'quote\'); ?>"')
    ftr = ftr.replace("<span>Staging preview, not live</span>", "")
    ftr = re.sub(r'\n<script src="[^"]*site\.js"></script>', "", ftr)
    ftr = ftr.replace("© The Roof Crew, Auckland", "© <?php echo esc_html( gmdate( 'Y' ) ); ?> The Roof Crew, Auckland")
    write("header.php", f'''<?php /* Generated by tools/build_wp_theme.py from the v2 design. Edit the generator, not this file. */ ?>
<!doctype html>
<html <?php language_attributes(); ?>>
<head>
<meta charset="<?php bloginfo( 'charset' ); ?>">
<meta name="viewport" content="width=device-width, initial-scale=1">
<?php wp_head(); ?>
</head>
<body <?php body_class(); ?>>
<?php wp_body_open(); ?>
{hdr}
<main>
''')
    write("footer.php", GEN + f'''</main>
{ftr}
<?php wp_footer(); ?>
</body>
</html>
''')

    # ---- assets (images, css, js, icons) from the static site
    for sub in ("css", "js", "icons", "img"):
        src = os.path.join(bv.OUT, "assets", sub)
        dst = os.path.join(THEME, "assets", sub)
        if os.path.isdir(dst):
            shutil.rmtree(dst)
        shutil.copytree(src, dst)
    shutil.copy2(os.path.join(THEME, "assets", "icons", "logo.png"), os.path.join(THEME, "screenshot.png")) if not os.path.exists(os.path.join(THEME, "screenshot.png")) else None

    # Sanity check: every generated PHP file must keep its tags balanced.
    for d, _, fs in os.walk(THEME):
        for f in fs:
            if f.endswith(".php"):
                t = open(os.path.join(d, f), encoding="utf-8").read()
                assert t.count("<?php") >= t.count("?>") - 0, f

    zpath = os.path.join(ROOT, "wordpress", "roofcrew-theme.zip")
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for d, _, fs in os.walk(THEME):
            for f in fs:
                full = os.path.join(d, f)
                z.write(full, os.path.join("roofcrew-theme", os.path.relpath(full, THEME)))
    print("theme built:", zpath)


if __name__ == "__main__":
    main()
